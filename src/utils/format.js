import { appConfig } from '../config/app.config.js'

const UNITS = [
  ['year', 31_536_000],
  ['month', 2_592_000],
  ['week', 604_800],
  ['day', 86_400],
  ['hour', 3_600],
  ['minute', 60],
]
const relative = new Intl.RelativeTimeFormat('en', { numeric: 'auto' })
const dateTime = new Intl.DateTimeFormat('en', { dateStyle: 'medium', timeStyle: 'short' })

/**
 * "5 minutes ago", "yesterday", "just now".
 * @param {string|Date} date
 * @param {number} now  Epoch ms.
 */
export function formatTimeAgo(date, now) {
  const time = Date.parse(date)
  if (Number.isNaN(time)) return ''
  // Future dates (feed timezone errors, clock skew) read as "just now" rather than "in 6 hours".
  const seconds = Math.min(0, Math.round((time - now) / 1000))
  if (Math.abs(seconds) < 45) return 'just now'
  for (const [unit, size] of UNITS) {
    if (Math.abs(seconds) >= size) return relative.format(Math.round(seconds / size), unit)
  }
  return relative.format(Math.round(seconds / 60), 'minute')
}

/** "Nov 14, 2026, 9:30 AM" */
export function formatDateTime(date) {
  const d = new Date(date)
  return Number.isNaN(d.getTime()) ? '' : dateTime.format(d)
}

/** 452000 → "7:32" */
export function formatClock(ms) {
  const total = Math.ceil(ms / 1000)
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, '0')}`
}

/**
 * Traceability line shown under every digest.
 * @param {{ ai_provider?: string|null, ai_model?: string|null, prompt_version?: string|null, news_source?: string|null }} digest
 * @returns {string} e.g. "Generated by gemini · gemini-3.6-flash · prompt v1 · news google_news_rss"
 */
export function formatProvenance(digest) {
  const { labels } = appConfig
  const parts = [
    `${labels.generatedBy} ${digest.ai_provider || 'unknown provider'}`,
    digest.ai_model || 'unknown model',
    `${labels.promptPrefix} ${digest.prompt_version || '?'}`,
  ]
  if (digest.news_source) parts.push(`${labels.newsSourcePrefix} ${digest.news_source}`)
  return parts.join(' · ')
}
